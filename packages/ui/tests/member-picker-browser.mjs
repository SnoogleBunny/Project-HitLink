import { chromium } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const prisma = new PrismaClient();
const browser = await chromium.launch({ headless: true });
const marker = `ui-picker-${Date.now()}`;
const childId = `${marker}-child`, guardianId = `${marker}-guardian`, grantId = `${marker}-grant`;
const workspaceId = "demo-workspace-flowstate";
try {
  await prisma.member.create({ data: { id: childId, workspaceId, fullName: "Picker Test Child", status: "ACTIVE" } });
  await prisma.guardian.create({ data: { id: guardianId, workspaceId, fullName: "Picker Test Guardian" } });
  await prisma.familyLink.create({ data: { workspaceId, guardianId, childMemberId: childId } });
  await prisma.memberPortalGrant.create({ data: { id: grantId, workspaceId, userId: "demo-user-member", memberId: childId, guardianId, verifiedByWorkspaceUserId: "demo-workspace-user-owner", verificationNote: "Temporary UI test fixture", canBook: false, canSign: false, canPay: false } });
  const page = await browser.newPage({ viewport: { width: 1048, height: 900 }, reducedMotion: "reduce" });
  await page.goto("http://localhost:3201/login");
  await page.getByLabel("Email").fill("demo-member@flowstate.local");
  await page.getByLabel("Password", { exact: true }).fill("MemberPass123!");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await page.locator(".hl-workspace-shell").waitFor();
  await page.goto("http://localhost:3201/app/schedule");
  const trigger = page.getByRole("button", { name: /Select member, currently/ });
  await trigger.click();
  const picker = page.getByRole("dialog", { name: "Choose a member" });
  await picker.waitFor();
  const anchor = await trigger.boundingBox(), desktopPicker = await picker.boundingBox();
  assert(desktopPicker.y >= anchor.y + anchor.height, "Desktop picker sits below its trigger");
  await mkdir("test-results/approved-ui", { recursive: true });
  await page.screenshot({ path: "test-results/approved-ui/member-picker-desktop.png" });
  await page.keyboard.press("Escape");
  assert(await trigger.evaluate((element) => element === document.activeElement));
  await page.setViewportSize({ width: 320, height: 900 });
  await trigger.click();
  const phonePicker = await picker.boundingBox();
  assert.equal(phonePicker.x, 0);
  assert.equal(Math.round(phonePicker.y + phonePicker.height), 900);
  await page.screenshot({ path: "test-results/approved-ui/member-picker-phone.png" });
  await picker.getByRole("button", { name: "Picker Test Child", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.hl-person-trigger')?.textContent.includes('Picker Test Child'));
  await page.reload();
  await page.getByRole("button", { name: "Select member, currently Picker Test Child", exact: true }).waitFor();
  // Exercise the existing generic dirty-form guard without creating a signed waiver fixture.
  await page.locator("main").evaluate((main) => { const form = document.createElement("form"); form.dataset.personContext = ""; const field = document.createElement("input"); field.id = "picker-draft-test"; form.append(field); main.append(form); });
  await page.locator("#picker-draft-test").fill("Unfinished form");
  await trigger.click();
  await picker.getByRole("button", { name: "Demo Member", exact: true }).click();
  const confirm = page.getByRole("dialog", { name: "Discard this unfinished form?" });
  await confirm.waitFor();
  await confirm.getByRole("button", { name: "Keep editing" }).click();
  assert.equal(await page.locator("#picker-draft-test").inputValue(), "Unfinished form");
  assert.match(await trigger.textContent(), /Picker Test Child/);
  await page.goto("http://localhost:3201/app/billing");
  await page.getByText("Your account", { exact: true }).waitFor();
  assert.equal(await trigger.count(), 0);
  await prisma.memberPortalGrant.update({ where: { id: grantId }, data: { revokedAt: new Date() } });
  await page.goto("http://localhost:3201/app/schedule");
  await page.locator(".hl-member-identity").waitFor();
  assert.match(await page.locator(".hl-member-identity").textContent(), /Demo Member/);
  assert.equal(await trigger.count(), 0);
  console.log("Member picker: desktop anchor, phone sheet, focus restore, persisted selection, dirty-form guard, payer scope and revoked-access fallback passed.");
} finally {
  await browser.close();
  await prisma.memberPortalGrant.deleteMany({ where: { id: grantId } });
  await prisma.familyLink.deleteMany({ where: { guardianId } });
  await prisma.guardian.deleteMany({ where: { id: guardianId } });
  await prisma.member.deleteMany({ where: { id: childId } });
  await prisma.$disconnect();
}
